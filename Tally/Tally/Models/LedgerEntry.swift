import Foundation
import SwiftData

/// A single ledger record: an expense, an income or a transfer between accounts.
///
/// Original-currency amounts and the base-currency conversion snapshot are stored
/// separately. Later exchange-rate edits therefore never rewrite history: the
/// snapshot records exactly which rate was used when the entry was saved.
@Model
final class LedgerEntry {
    var id: UUID = UUID()
    var kindRaw: String = TransactionKind.expense.rawValue

    /// Always positive, expressed in `currencyCode` (the source account's currency).
    var amountRaw: String = "0"
    var currencyCode: String = "CNY"

    var date: Date = Date()
    var note: String = ""

    var account: Account?
    /// Destination account for transfers.
    var toAccount: Account?
    /// Amount credited to `toAccount`, in the destination currency (transfers only).
    var toAmountRaw: String = ""

    var category: LedgerCategory?
    var tags: [Tag]? = []

    // Base-currency snapshot taken at save time.
    var baseCurrencyCode: String = "CNY"
    var rateToBaseRaw: String = "1"
    var baseAmountRaw: String = "0"

    var isDemo: Bool = false
    var createdAt: Date = Date()
    var updatedAt: Date = Date()

    /// Merchant or counterparty (optional).
    var payee: String = ""
    /// Fee (transfer or expense) in the source currency, booked as spending under `feeCategoryIDRaw`.
    var feeRaw: String = ""
    var feeCategoryIDRaw: String = ""
    /// Discount on an expense: the account pays `amount − discount + fee`; the discount
    /// lowers the spending counted in the expense's categories (it is never income).
    var discountRaw: String = ""
    /// Refunds: the original transaction (kept as an ID so deleting it never loses the refund).
    var refundOfIDRaw: String = ""
    /// Balance adjustments: signed change and the balance before the adjustment (audit trail).
    var adjustmentDeltaRaw: String = ""
    var adjustmentPreviousBalanceRaw: String = ""
    /// Entries generated by a recurring rule: rule ID and the scheduled day (de-duplication key).
    var recurringRuleIDRaw: String = ""
    var occurrenceDate: Date?

    @Relationship(deleteRule: .cascade, inverse: \TransactionSplit.entry)
    var splits: [TransactionSplit]? = []

    /// Relationships (account, category, tags…) are attached after the entry has been
    /// inserted into a context — the safest order for SwiftData on every iOS 17 release.
    init(kind: TransactionKind, amount: Decimal, currencyCode: String, date: Date, note: String = "", isDemo: Bool = false) {
        self.id = UUID()
        self.kindRaw = kind.rawValue
        self.amountRaw = DecimalCodec.encode(amount.magnitudeValue)
        self.currencyCode = currencyCode
        self.date = date
        self.note = note
        self.isDemo = isDemo
        self.createdAt = Date()
        self.updatedAt = Date()
    }

    var kind: TransactionKind {
        get { TransactionKind(rawValue: kindRaw) ?? .expense }
        set { kindRaw = newValue.rawValue }
    }

    var amount: Decimal {
        get { DecimalCodec.decode(amountRaw) }
        set { amountRaw = DecimalCodec.encode(newValue.magnitudeValue) }
    }

    /// Credited amount for transfers. Falls back to `amount` for same-currency transfers.
    var toAmount: Decimal {
        get { toAmountRaw.isEmpty ? amount : DecimalCodec.decode(toAmountRaw) }
        set { toAmountRaw = DecimalCodec.encode(newValue.magnitudeValue) }
    }

    var rateToBase: Decimal {
        get { DecimalCodec.decode(rateToBaseRaw) }
        set { rateToBaseRaw = DecimalCodec.encode(newValue) }
    }

    var baseAmount: Decimal {
        get { DecimalCodec.decode(baseAmountRaw) }
        set { baseAmountRaw = DecimalCodec.encode(newValue) }
    }

    var currency: CurrencyInfo { CurrencyInfo.info(for: currencyCode) }

    var tagList: [Tag] { (tags ?? []).sorted { $0.name < $1.name } }

    var discount: Decimal {
        get { DecimalCodec.decode(discountRaw) }
        set { discountRaw = newValue.isZero ? "" : DecimalCodec.encode(newValue.magnitudeValue) }
    }

    /// What left (or entered) the account for this entry, in its currency.
    var paidAmount: Decimal {
        switch kind {
        case .expense: amount - discount + fee
        case .transfer: amount + fee
        default: amount
        }
    }

    var fee: Decimal {
        get { DecimalCodec.decode(feeRaw) }
        set { feeRaw = newValue == 0 ? "" : DecimalCodec.encode(newValue.magnitudeValue) }
    }

    var adjustmentDelta: Decimal {
        get { DecimalCodec.decode(adjustmentDeltaRaw) }
        set { adjustmentDeltaRaw = DecimalCodec.encode(newValue) }
    }

    var splitList: [TransactionSplit] { (splits ?? []).sorted { $0.sortOrder < $1.sortOrder } }

    var isSplit: Bool { !(splits ?? []).isEmpty }

    /// Whether a base-currency snapshot exists (false = pending conversion).
    var hasSnapshot: Bool { !rateToBaseRaw.isEmpty && !baseAmountRaw.isEmpty }

    /// Transfers into a credit card or debt account are repayments.
    var isRepayment: Bool { kind == .transfer && (toAccount?.kind.isLiability ?? false) }

    /// Title used in lists: category name, "From → To" for transfers, or the kind.
    var displayTitle: String {
        switch kind {
        case .transfer:
            let from = account?.name ?? "—"
            let to = toAccount?.name ?? "—"
            return "\(from) → \(to)"
        case .adjustment:
            return TransactionKind.adjustment.title
        case .expense, .income, .refund:
            if isSplit { return String(localized: "Split") }
            return category?.name ?? String(localized: "Uncategorized")
        }
    }

    var displaySymbol: String {
        switch kind {
        case .transfer: isRepayment ? "creditcard.and.123" : "arrow.left.arrow.right"
        case .adjustment: "slider.horizontal.3"
        case .refund: "arrow.uturn.backward"
        default: isSplit ? "square.split.2x2" : (category?.symbolName ?? "questionmark")
        }
    }

    var displayColorHex: String {
        switch kind {
        case .transfer: "5E8BFF"
        case .adjustment: "7D8BA6"
        case .refund: "47B5D9"
        default: isSplit ? "6C7BF2" : (category?.colorHex ?? "8E8E93")
        }
    }
}
